export const TAJIKISTAN_REGION_NAMES: string[] = TAJIKISTAN_REGIONS.map((r) => r.name);

const ALL_DISTRICTS: string[] = TAJIKISTAN_REGIONS.flatMap((r) => r.districts);

// Поле "Регион" многие заполняют названием своего города (Худжанд, Бохтар,
// Кулоб...), а не официальным названием области — если подсказывать только
// 5 областей, при вводе города подсказок не будет вообще (выглядит как "нет
// подсказки"). Поэтому в подсказку для "Региона" подмешаны все города/районы
// тоже — выбор города как региона отправляется как есть (поле свободное),
// а "Район" при нераспознанном регионе и так честно показывает районы всех
// областей (см. getDistrictsForRegion).
export const TAJIKISTAN_REGION_SUGGESTIONS: string[] = [...TAJIKISTAN_REGION_NAMES, ...ALL_DISTRICTS];

// Регион свободный текст (не выбор из фиксированного списка), поэтому если он
// не распознан — честно предлагаем полный список районов всех областей,
// а не пустую подсказку.
export function getDistrictsForRegion(region: string): string[] {
  const normalized = region.trim().toLowerCase();
  const match = TAJIKISTAN_REGIONS.find((r) => r.name.toLowerCase() === normalized);
  return match ? match.districts : ALL_DISTRICTS;
}
